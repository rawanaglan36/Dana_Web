function setLanguage(lang) {
  const html = document.documentElement;
  html.setAttribute('lang', lang);
  html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  updateMobileOverlay(lang);

  localStorage.setItem('dana-lang', lang);
}

function updateMobileOverlay(lang) {
  const overlay = document.querySelector('.nav__mobile-overlay');
  if (!overlay) return;

  const t = translations[lang];
  const links = overlay.querySelectorAll('a');
  const map = ['nav.home', 'nav.about', 'nav.why', 'nav.services', 'nav.faq', 'nav.contact'];
  links.forEach((link, i) => {
    if (map[i] && t[map[i]]) link.textContent = t[map[i]];
  });
}

document.addEventListener('DOMContentLoaded', () => {

  // Preloader (hide on load + max timeout fallback)
  const preloader = document.querySelector('.preloader');
  const hidePreloader = () => preloader?.classList.add('is-hidden');
  window.addEventListener('load', hidePreloader, { once: true });
  setTimeout(hidePreloader, 3000);

  // Scroll reveal animations
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const revealEls = document.querySelectorAll('.reveal');
  if (!prefersReducedMotion && revealEls.length) {
    const revealObserver = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const delayAttr = el.getAttribute('data-reveal-delay');
        if (delayAttr) el.style.setProperty('--reveal-delay', `${delayAttr}ms`);
        el.classList.add('reveal--visible');
        obs.unobserve(el);
      });
    }, { threshold: 0.15, rootMargin: '0px 0px -10% 0px' });

    revealEls.forEach(el => revealObserver.observe(el));
  } else {
    revealEls.forEach(el => el.classList.add('reveal--visible'));
  }

  // FAQ Accordion
  const faqItems = document.querySelectorAll('.faq-item');

  function setFaqOpen(item, open) {
    const header = item.querySelector('.faq-item__header');
    const body = item.querySelector('.faq-item__body');
    const icon = item.querySelector('.faq-item__icon-img');

    item.classList.toggle('faq-item--open', open);
    header?.setAttribute('aria-expanded', open ? 'true' : 'false');
    if (icon) icon.src = open ? 'assets/icon-remove.svg' : 'assets/icon-add-circle.svg';

    if (!body) return;
    if (!open) {
      body.style.maxHeight = '0px';
      return;
    }

    body.style.maxHeight = `${body.scrollHeight}px`;
  }

  faqItems.forEach(item => {
    const header = item.querySelector('.faq-item__header');
    if (!header) return;

    header.addEventListener('click', () => {
      const isOpen = item.classList.contains('faq-item--open');
      faqItems.forEach(other => setFaqOpen(other, false));
      setFaqOpen(item, !isOpen);
    });
  });

  // Ensure initially open FAQ is measured
  requestAnimationFrame(() => {
    const initiallyOpen = document.querySelector('.faq-item.faq-item--open');
    if (initiallyOpen) setFaqOpen(initiallyOpen, true);
  });

  // Service Tabs
  const tabs = document.querySelectorAll('.tab');
  const tabsWrap = document.querySelector('.services__tabs');
  const servicesCards = document.querySelector('.services__cards');

  const serviceTabData = {
    parents: [
      {
        iconSrc: 'assets/icon-growth.svg',
        iconRound: false,
        titleKey: 'services.card1.title',
        descKey: 'services.card1.desc',
      },
      {
        iconSrc: 'assets/icon-injection.svg',
        iconRound: true,
        titleKey: 'services.card2.title',
        descKey: 'services.card2.desc',
      },
      {
        iconSrc: 'assets/icon-milestones.svg',
        iconRound: false,
        titleKey: 'services.card3.title',
        descKey: 'services.card3.desc',
      },
    ],
    doctors: [
      {
        iconSrc: 'assets/icon-scheduling.svg',
        iconRound: true,
        titleKey: 'services.doctors.card1.title',
        descKey: 'services.doctors.card1.desc',
      },
      {
        iconSrc: 'assets/icon-ehr.svg',
        iconRound: true,
        titleKey: 'services.doctors.card2.title',
        descKey: 'services.doctors.card2.desc',
      },
      {
        iconSrc: 'assets/icon-messaging.svg',
        iconRound: true,
        titleKey: 'services.doctors.card3.title',
        descKey: 'services.doctors.card3.desc',
      },
    ],
  };

  function renderServiceCards(tabName) {
    if (!servicesCards) return;
    const items = serviceTabData[tabName] || serviceTabData.parents;

    servicesCards.innerHTML = items
      .map((item, idx) => {
        const delay = idx * 80;
        const iconClass = item.iconRound ? 'service-card__icon service-card__icon--round' : 'service-card__icon';
        return `
          <div class="service-card reveal reveal--visible" data-reveal-delay="${delay}">
            <div class="${iconClass}">
              <img src="${item.iconSrc}" alt="" />
            </div>
            <h3 class="service-card__title" data-i18n="${item.titleKey}"></h3>
            <p class="service-card__desc" data-i18n="${item.descKey}"></p>
          </div>
        `;
      })
      .join('');

    const lang = document.documentElement.getAttribute('lang') || 'en';
    setLanguage(lang);
  }

  function updateTabIndicator() {
    if (!tabsWrap) return;
    const active = tabsWrap.querySelector('.tab--active');
    if (!active) return;
    const wrapRect = tabsWrap.getBoundingClientRect();
    const activeRect = active.getBoundingClientRect();
    const left = Math.max(0, activeRect.left - wrapRect.left);
    tabsWrap.style.setProperty('--tab-left', `${left}px`);
    tabsWrap.style.setProperty('--tab-width', `${activeRect.width}px`);
  }

  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.forEach(t => t.classList.remove('tab--active'));
      tab.classList.add('tab--active');
      updateTabIndicator();
      const target = tab.getAttribute('data-service-tab') || 'parents';
      renderServiceCards(target);
    });
  });

  updateTabIndicator();
  // Ensure correct initial content (in case HTML changes)
  renderServiceCards(tabsWrap?.querySelector('.tab--active')?.getAttribute('data-service-tab') || 'parents');
  window.addEventListener('resize', updateTabIndicator);

  // Mobile hamburger menu
  const hamburger = document.querySelector('.nav__hamburger');
  let overlay = null;

  if (hamburger) {
    hamburger.addEventListener('click', () => {
      if (!overlay) {
        overlay = document.createElement('div');
        overlay.className = 'nav__mobile-overlay';
        const lang = document.documentElement.getAttribute('lang') || 'en';
        const t = translations[lang];
        overlay.innerHTML = `
          <button class="nav__mobile-close" aria-label="Close menu">&times;</button>
          <a href="#hero" class="nav__link--active">${t['nav.home']}</a>
          <a href="#about">${t['nav.about']}</a>
          <a href="#why">${t['nav.why']}</a>
          <a href="#services">${t['nav.services']}</a>
          <a href="#faq">${t['nav.faq']}</a>
          <a href="#contact">${t['nav.contact']}</a>
        `;
        document.body.appendChild(overlay);

        overlay.querySelector('.nav__mobile-close').addEventListener('click', closeMenu);
        overlay.querySelectorAll('a').forEach(link => {
          link.addEventListener('click', (e) => {
            closeMenu();
            const targetId = link.getAttribute('href');
            const target = document.querySelector(targetId);
            if (target) {
              e.preventDefault();
              setTimeout(() => {
                target.scrollIntoView({ behavior: 'smooth', block: 'start' });
              }, 300);
            }
          });
        });
      }

      overlay.classList.add('open');
      hamburger.classList.add('open');
      document.body.style.overflow = 'hidden';
    });
  }

  function closeMenu() {
    if (overlay) overlay.classList.remove('open');
    if (hamburger) hamburger.classList.remove('open');
    document.body.style.overflow = '';
  }

  // Smooth scroll for nav links
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', (e) => {
      const targetId = anchor.getAttribute('href');
      if (targetId === '#') return;
      const target = document.querySelector(targetId);
      if (target) {
        e.preventDefault();
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    });
  });

  // Back to top button
  const backToTop = document.querySelector('.back-to-top');
  const heroSection = document.querySelector('#hero');
  if (backToTop) {
    const toggleBackToTop = () => {
      const threshold = heroSection ? heroSection.offsetHeight * 0.6 : 500;
      backToTop.classList.toggle('is-visible', window.scrollY > threshold);
    };

    toggleBackToTop();
    window.addEventListener('scroll', () => requestAnimationFrame(toggleBackToTop), { passive: true });
    window.addEventListener('resize', () => requestAnimationFrame(toggleBackToTop));

    backToTop.addEventListener('click', () => {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }

  // Language toggle
  const translateBtn = document.querySelector('.nav__icon-btn[aria-label="Translate"]');
  const savedLang = localStorage.getItem('dana-lang') || 'en';
  if (savedLang !== 'en') setLanguage(savedLang);

  if (translateBtn) {
    translateBtn.addEventListener('click', () => {
      const current = document.documentElement.getAttribute('lang') || 'en';
      const next = current === 'en' ? 'ar' : 'en';
      setLanguage(next);
    });
  }

  // Dark mode toggle
  const moonBtn = document.querySelector('.nav__icon-btn[aria-label="Dark mode"]');
  const savedTheme = localStorage.getItem('dana-theme');
  if (savedTheme) {
    document.documentElement.setAttribute('data-theme', savedTheme);
  }

  if (moonBtn) {
    moonBtn.addEventListener('click', () => {
      const current = document.documentElement.getAttribute('data-theme');
      const next = current === 'dark' ? 'light' : 'dark';
      document.documentElement.setAttribute('data-theme', next);
      localStorage.setItem('dana-theme', next);
    });
  }

  // Navbar scroll animation
  const nav = document.getElementById('nav');
  const sections = document.querySelectorAll('section[id], footer[id]');
  const navLinks = document.querySelectorAll('.nav__link');

  const updateActiveNavLink = () => {
    const scrollY = window.scrollY + 200;
    const pageBottom = window.scrollY + window.innerHeight >= document.body.scrollHeight - 50;

    if (pageBottom) {
      const lastSection = [...sections].reverse().find(s =>
        document.querySelector(`.nav__link[href="#${s.id}"]`)
      );
      if (lastSection) {
        navLinks.forEach(l => l.classList.remove('nav__link--active'));
        const target = document.querySelector(`.nav__link[href="#${lastSection.id}"]`);
        if (target) target.classList.add('nav__link--active');
        return;
      }
    }

    let currentId = '';
    sections.forEach(section => {
      if (scrollY >= section.offsetTop && scrollY < section.offsetTop + section.offsetHeight) {
        currentId = section.id;
      }
    });

    if (currentId) {
      navLinks.forEach(link => {
        link.classList.toggle('nav__link--active', link.getAttribute('href') === `#${currentId}`);
      });
    }
  };

  let scrollTicking = false;
  window.addEventListener('scroll', () => {
    if (!scrollTicking) {
      requestAnimationFrame(() => {
        nav.classList.toggle('scrolled', window.scrollY > 200);
        updateActiveNavLink();
        scrollTicking = false;
      });
      scrollTicking = true;
    }
  }, { passive: true });

});
